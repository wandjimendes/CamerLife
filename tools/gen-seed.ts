/**
 * Renders packages/shared/src/layout.ts into supabase/seed.sql
 * (towns, buildings, units and a few admin-created job openings).
 * Idempotent: uses ON CONFLICT on slugs/ids.
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { TOWNS } from "../packages/shared/src/index";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "supabase/seed.sql");

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const n = (v: number | null) => (v === null ? "null" : String(v));

interface JobSeed {
  buildingSlug: string;
  title: string;
  description: string;
  salary: number;
  slots: number;
}

const JOBS: JobSeed[] = [
  { buildingSlug: "douala-hospital", title: "Nurse", description: "Care for patients at Laquintinie. 5 minute shifts.", salary: 25_000, slots: 4 },
  { buildingSlug: "douala-hospital", title: "Receptionist", description: "Welcome patients and manage the front desk.", salary: 15_000, slots: 2 },
  { buildingSlug: "douala-hospital", title: "Doctor", description: "Senior position. Experience required.", salary: 60_000, slots: 1 },
];

function main() {
  const lines: string[] = [];
  lines.push("-- Generated by tools/gen-seed.ts - do not edit by hand. Run: npm run gen:seed");
  lines.push("begin;");
  lines.push("");

  lines.push("insert into public.towns (id, name, map_key, spawn_x, spawn_y) values");
  const townRows = [
    ...TOWNS.map((t) => `  (${q(t.id)}, ${q(t.name)}, ${q(t.mapKey)}, ${t.spawn.x}, ${t.spawn.y})`),
    // Yaoundé exists as a destination; its map ships in Phase 2.
    `  ('yaounde', 'Yaoundé', 'yaounde', 20, 17)`,
  ];
  lines.push(townRows.join(",\n"));
  lines.push("on conflict (id) do update set name = excluded.name, map_key = excluded.map_key, spawn_x = excluded.spawn_x, spawn_y = excluded.spawn_y;");
  lines.push("");

  lines.push("insert into public.buildings (slug, town_id, name, kind, x, y, w, h, door_x, door_y, is_facility) values");
  const bRows: string[] = [];
  for (const t of TOWNS) {
    for (const b of t.buildings) {
      bRows.push(
        `  (${q(b.slug)}, ${q(t.id)}, ${q(b.name)}, ${q(b.kind)}, ${b.x}, ${b.y}, ${b.w}, ${b.h}, ${b.doorX}, ${b.doorY}, ${b.isFacility})`,
      );
    }
  }
  lines.push(bRows.join(",\n"));
  lines.push(
    "on conflict (slug) do update set name = excluded.name, kind = excluded.kind, x = excluded.x, y = excluded.y, w = excluded.w, h = excluded.h, door_x = excluded.door_x, door_y = excluded.door_y, is_facility = excluded.is_facility;",
  );
  lines.push("");

  lines.push("insert into public.units (slug, building_id, kind, label, listing_status, sale_price, rent_price, interior_w, interior_h) values");
  const uRows: string[] = [];
  for (const t of TOWNS) {
    for (const b of t.buildings) {
      for (const u of b.units) {
        uRows.push(
          `  (${q(u.slug)}, (select id from public.buildings where slug = ${q(b.slug)}), ${q(u.kind)}, ${q(u.label)}, ${q(u.listing)}, ${n(u.salePrice)}, ${n(u.rentPrice)}, ${u.interiorW}, ${u.interiorH})`,
        );
      }
    }
  }
  lines.push(uRows.join(",\n"));
  // never overwrite ownership / listings of existing units on re-seed
  lines.push("on conflict (slug) do update set label = excluded.label, interior_w = excluded.interior_w, interior_h = excluded.interior_h;");
  lines.push("");

  lines.push("-- Job openings (normally created by an admin from the Admin Panel)");
  for (const j of JOBS) {
    lines.push(
      `insert into public.jobs (town_id, building_id, title, description, salary, slots, status)\n` +
        `select b.town_id, b.id, ${q(j.title)}, ${q(j.description)}, ${j.salary}, ${j.slots}, 'open'\n` +
        `  from public.buildings b where b.slug = ${q(j.buildingSlug)}\n` +
        `  and not exists (select 1 from public.jobs x where x.building_id = b.id and x.title = ${q(j.title)});`,
    );
  }
  lines.push("");
  lines.push("commit;");
  lines.push("");

  writeFileSync(OUT, lines.join("\n"));
  console.log(`Seed written: ${OUT}`);
}

main();
